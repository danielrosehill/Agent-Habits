#!/usr/bin/env python3
"""Tooling for a personal SOP library.

Python 3 standard library only — no PyYAML, no install step. The front-matter
parser below understands the subset of YAML the SOP format actually uses
(scalars, quoted scalars, inline `[a, b]` lists and block `- item` lists). It
is deliberately not a YAML implementation; anything fancier is rejected by
`validate` rather than silently half-parsed.

Library location, in order of precedence:

    $CLAUDE_SOPS_DIR
    ~/.claude-plugins/habits/config.json  ->  {"library": "..."}
    $CLAUDE_USER_DATA/sops
    ~/.claude-user-data/sops

SOP files sit directly in that folder, one per procedure — open it and you see
`foo.md`, not a nested tree. `INDEX.md` and `README.md` are reserved names and
are never treated as SOPs; `archive/` holds retired ones.

Usage:
    sop.py path                     print the resolved library path
    sop.py repo                     print the enclosing git repo root, if any
    sop.py init [DIR]               scaffold a library (idempotent)
    sop.py list [--tag T] [--stale DAYS] [--json]
    sop.py show ID                  print one SOP verbatim
    sop.py new ID --title T [--trigger S] [--tags a,b]
    sop.py index                    rebuild INDEX.md from front matter
    sop.py validate [ID ...]        check front matter, exit 1 on error
    sop.py retire ID                move to archive/ and reindex
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

PLUGIN_ROOT = Path(__file__).resolve().parent.parent
VAULT = Path.home() / ".claude-plugins" / "habits"
CONFIG = VAULT / "config.json"
DEFAULT_USER_DATA = Path.home() / ".claude-user-data"

# Filenames in the library that are never SOPs.
RESERVED = {"INDEX.md", "README.md"}

REQUIRED = ("id", "title", "trigger", "last_verified")
AUTONOMY = ("auto", "confirm", "confirm-each", "manual")
FREQUENCY = ("daily", "weekly", "monthly", "quarterly", "yearly", "occasional", "rare")
ID_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
LIST_KEYS = ("tags", "requires", "supersedes")

INDEX_HEADER = "<!-- generated by sop.py index — edit the SOPs, not this file -->"


# --------------------------------------------------------------------------
# location
# --------------------------------------------------------------------------

def read_config() -> dict:
    if CONFIG.is_file():
        try:
            return json.loads(CONFIG.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            die(f"{CONFIG} is not valid JSON: {exc}")
    return {}


def user_data_root() -> Path:
    """Root for user content. $CLAUDE_USER_DATA is the shared cross-plugin
    override; the default is a readable folder in $HOME rather than an XDG
    data directory, because this content is meant to be browsed by hand."""
    env = os.environ.get("CLAUDE_USER_DATA")
    return Path(env).expanduser() if env else DEFAULT_USER_DATA


def library_path() -> Path:
    env = os.environ.get("CLAUDE_SOPS_DIR")
    if env:
        return Path(env).expanduser()
    configured = read_config().get("library")
    if configured:
        return Path(configured).expanduser()
    return user_data_root() / "sops"


def sop_files(lib: Path) -> list[Path]:
    """Every SOP in the library. Flat — one file per procedure, no nesting."""
    return sorted(p for p in lib.glob("*.md") if p.name not in RESERVED)


def repo_root(lib: Path) -> Path | None:
    """The git repo the library sits in, which is often a level or more above it."""
    try:
        out = subprocess.run(
            ["git", "-C", str(lib), "rev-parse", "--show-toplevel"],
            capture_output=True, text=True, check=True,
        ).stdout.strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        return None
    return Path(out) if out else None


# --------------------------------------------------------------------------
# front matter
# --------------------------------------------------------------------------

def _scalar(raw: str):
    raw = raw.strip()
    if len(raw) >= 2 and raw[0] == raw[-1] and raw[0] in "\"'":
        return raw[1:-1]
    if raw.startswith("[") and raw.endswith("]"):
        inner = raw[1:-1].strip()
        if not inner:
            return []
        return [_scalar(part) for part in inner.split(",")]
    return raw


def parse_front_matter(text: str) -> tuple[dict, str]:
    """Return (front_matter, body). Missing front matter yields ({}, text)."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return {}, text
    try:
        end = next(i for i in range(1, len(lines)) if lines[i].strip() == "---")
    except StopIteration:
        return {}, text

    data: dict = {}
    key = None
    for line in lines[1:end]:
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if line.lstrip().startswith("- ") and key is not None:
            data.setdefault(key, [])
            if isinstance(data[key], list):
                data[key].append(_scalar(line.lstrip()[2:]))
            continue
        if ":" not in line:
            continue
        key, _, raw = line.partition(":")
        key = key.strip()
        value = _scalar(raw)
        data[key] = [] if value == "" and key in LIST_KEYS else value

    body = "\n".join(lines[end + 1:]).lstrip("\n")
    return data, body


def load_sops(lib: Path) -> list[tuple[Path, dict, str]]:
    if not lib.is_dir():
        die(f"no SOP library at {lib} — run `sop.py init` first")
    out = []
    for path in sop_files(lib):
        fm, body = parse_front_matter(path.read_text(encoding="utf-8"))
        out.append((path, fm, body))
    return out


# --------------------------------------------------------------------------
# helpers
# --------------------------------------------------------------------------

def die(msg: str, code: int = 1):
    print(f"error: {msg}", file=sys.stderr)
    sys.exit(code)


def today() -> str:
    return dt.date.today().isoformat()


def age_days(datestr: str) -> int | None:
    try:
        return (dt.date.today() - dt.date.fromisoformat(datestr)).days
    except (ValueError, TypeError):
        return None


def as_list(value) -> list:
    if value is None or value == "":
        return []
    return value if isinstance(value, list) else [value]


# --------------------------------------------------------------------------
# commands
# --------------------------------------------------------------------------

def cmd_path(args):
    print(library_path())


def cmd_repo(args):
    root = repo_root(library_path())
    if root is None:
        sys.exit(1)
    print(root)


def cmd_init(args):
    lib = Path(args.dir).expanduser() if args.dir else library_path()
    lib.mkdir(parents=True, exist_ok=True)
    (lib / "archive").mkdir(exist_ok=True)

    readme = lib / "README.md"
    if not readme.is_file():
        src = PLUGIN_ROOT / "templates" / "library-README.md"
        readme.write_text(src.read_text(encoding="utf-8"), encoding="utf-8")

    gitignore = lib / ".gitignore"
    if not gitignore.is_file():
        gitignore.write_text("*.tmp\n.DS_Store\n", encoding="utf-8")

    write_index(lib)
    print(lib)


def cmd_new(args):
    lib = library_path()
    if not ID_RE.match(args.id):
        die(f"id must be kebab-case: {args.id!r}")
    if f"{args.id}.md" in RESERVED or args.id in ("index", "readme", "archive"):
        die(f"{args.id!r} is a reserved name in the library")
    target = lib / f"{args.id}.md"
    if target.exists():
        die(f"{target} already exists — use sop.py show/edit instead")
    target.parent.mkdir(parents=True, exist_ok=True)

    tmpl = (PLUGIN_ROOT / "templates" / "sop.template.md").read_text(encoding="utf-8")
    tmpl = tmpl.replace("PLACEHOLDER_ID", args.id)
    tmpl = tmpl.replace("PLACEHOLDER_TITLE", args.title)
    tmpl = tmpl.replace("PLACEHOLDER_DATE", today())
    if args.trigger:
        tmpl = tmpl.replace(
            "trigger: describe the situation in which this procedure applies",
            f"trigger: {args.trigger}",
        )
    if args.tags:
        tags = [t.strip() for t in args.tags.split(",") if t.strip()]
        tmpl = tmpl.replace("tags: []", "tags: [" + ", ".join(tags) + "]")

    target.write_text(tmpl, encoding="utf-8")
    write_index(lib)
    print(target)


def cmd_show(args):
    lib = library_path()
    path = lib / f"{args.id}.md"
    if not path.is_file() or path.name in RESERVED:
        die(f"no SOP with id {args.id!r} in {lib}")
    sys.stdout.write(path.read_text(encoding="utf-8"))


def cmd_list(args):
    lib = library_path()
    rows = []
    for path, fm, _ in load_sops(lib):
        if args.tag and args.tag not in as_list(fm.get("tags")):
            continue
        age = age_days(str(fm.get("last_verified", "")))
        if args.stale is not None and (age is None or age < args.stale):
            continue
        rows.append(
            {
                "id": fm.get("id", path.stem),
                "title": fm.get("title", ""),
                "trigger": fm.get("trigger", ""),
                "tags": as_list(fm.get("tags")),
                "autonomy": fm.get("autonomy", "confirm"),
                "last_verified": fm.get("last_verified", ""),
                "age_days": age,
                "file": str(path),
            }
        )

    if args.json:
        print(json.dumps(rows, indent=2, ensure_ascii=False))
        return
    if not rows:
        print(f"(no SOPs in {lib})")
        return
    width = max(len(r["id"]) for r in rows)
    for r in rows:
        flag = " [stale]" if r["age_days"] is not None and r["age_days"] > 365 else ""
        print(f"{r['id']:<{width}}  {r['title']}{flag}")


def write_index(lib: Path) -> Path:
    rows = []
    lib.mkdir(parents=True, exist_ok=True)
    for path in sop_files(lib):
        fm, _ = parse_front_matter(path.read_text(encoding="utf-8"))
        rows.append(
            (
                fm.get("id", path.stem),
                fm.get("title", ""),
                fm.get("trigger", ""),
                ", ".join(as_list(fm.get("tags"))),
                fm.get("autonomy", "confirm"),
                str(fm.get("last_verified", "")),
            )
        )

    out = [
        INDEX_HEADER,
        "",
        "# SOP index",
        "",
        f"{len(rows)} procedure(s). Read this file to choose one; read only the "
        "chosen `<id>.md` after that.",
        "",
        "| ID | Title | Use when | Tags | Autonomy | Verified |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    stale = False
    for r in rows:
        cells = [c.replace("|", "\\|") for c in r]
        age = age_days(r[5])
        verified = r[5]
        if age is not None and age > 365:
            verified, stale = f"{r[5]} ⚠️", True
        out.append(
            f"| [`{cells[0]}`]({cells[0]}.md) | {cells[1]} | {cells[2]} | "
            f"{cells[3]} | {cells[4]} | {verified} |"
        )
    if stale:
        out += ["", "⚠️ = not verified in over a year. Confirm before trusting it."]
    out.append("")

    index = lib / "INDEX.md"
    index.write_text("\n".join(out), encoding="utf-8")
    return index


def cmd_index(args):
    print(write_index(library_path()))


def cmd_validate(args):
    lib = library_path()
    problems = []
    seen: dict[str, Path] = {}

    for path, fm, body in load_sops(lib):
        where = path.name
        if not fm:
            problems.append(f"{where}: no YAML front matter")
            continue
        for key in REQUIRED:
            if not fm.get(key):
                problems.append(f"{where}: missing required field `{key}`")
        sid = str(fm.get("id", ""))
        if sid and not ID_RE.match(sid):
            problems.append(f"{where}: id {sid!r} is not kebab-case")
        if sid and sid != path.stem:
            problems.append(f"{where}: id {sid!r} does not match filename")
        if sid in seen:
            problems.append(f"{where}: duplicate id, also in {seen[sid].name}")
        seen[sid] = path
        lv = str(fm.get("last_verified", ""))
        if lv and not DATE_RE.match(lv):
            problems.append(f"{where}: last_verified {lv!r} is not YYYY-MM-DD")
        aut = fm.get("autonomy", "confirm")
        if aut not in AUTONOMY:
            problems.append(f"{where}: autonomy {aut!r} not one of {AUTONOMY}")
        freq = fm.get("frequency")
        if freq and freq not in FREQUENCY:
            problems.append(f"{where}: frequency {freq!r} not one of {FREQUENCY}")
        for key in LIST_KEYS:
            if key in fm and not isinstance(fm[key], list):
                problems.append(f"{where}: `{key}` must be a list")
        if "## Steps" not in body:
            problems.append(f"{where}: no `## Steps` section")
        if "PLACEHOLDER" in body or "PLACEHOLDER" in json.dumps(fm, default=str):
            problems.append(f"{where}: template placeholder left in place")

    if args.id:
        wanted = set(args.id)
        problems = [p for p in problems if p.split(":")[0].removesuffix(".md") in wanted]

    for p in problems:
        print(p)
    if problems:
        sys.exit(1)
    print(f"ok — {len(seen)} SOP(s) valid")


def cmd_retire(args):
    lib = library_path()
    src = lib / f"{args.id}.md"
    if not src.is_file() or src.name in RESERVED:
        die(f"no SOP with id {args.id!r}")
    archive = lib / "archive"
    archive.mkdir(exist_ok=True)
    dest = archive / f"{today()}-{args.id}.md"
    shutil.move(str(src), str(dest))
    write_index(lib)
    print(dest)


def main():
    ap = argparse.ArgumentParser(prog="sop.py", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    sub.add_parser("path").set_defaults(func=cmd_path)
    sub.add_parser("repo").set_defaults(func=cmd_repo)

    p = sub.add_parser("init")
    p.add_argument("dir", nargs="?")
    p.set_defaults(func=cmd_init)

    p = sub.add_parser("list")
    p.add_argument("--tag")
    p.add_argument("--stale", type=int, metavar="DAYS")
    p.add_argument("--json", action="store_true")
    p.set_defaults(func=cmd_list)

    p = sub.add_parser("show")
    p.add_argument("id")
    p.set_defaults(func=cmd_show)

    p = sub.add_parser("new")
    p.add_argument("id")
    p.add_argument("--title", required=True)
    p.add_argument("--trigger")
    p.add_argument("--tags")
    p.set_defaults(func=cmd_new)

    sub.add_parser("index").set_defaults(func=cmd_index)

    p = sub.add_parser("validate")
    p.add_argument("id", nargs="*")
    p.set_defaults(func=cmd_validate)

    p = sub.add_parser("retire")
    p.add_argument("id")
    p.set_defaults(func=cmd_retire)

    args = ap.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
